/**
 * Real central-city coordinates used for the six interactive region
 * beacons, so beacon placement is "a real place" rather than an abstract
 * centroid. Looked up by name from MAJOR_CITIES above (falls back to the
 * literal coordinates if a name ever drifts out of sync with the list).
 */
function findCity(name: string): CityPoint {
  const found = MAJOR_CITIES.find((c) => c.name === name);
  if (!found) throw new Error(`majorCities: expected beacon city "${name}" to exist in MAJOR_CITIES`);
  return found;
}

