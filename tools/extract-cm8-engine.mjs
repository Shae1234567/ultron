/**
 * Dumps CM8's live nutrition tables into a typed module (src/cm8/foods.ts).
 *
 * The food database is built at runtime by a helper function rather than
 * written as a literal, so it cannot be lifted textually the way the content
 * is. Instead this runs CM8's own engine in a sandbox and serialises the
 * finished tables - the numbers in Atlas are then provably the same numbers
 * CM8 uses, not a retyped approximation.
 *
 *   node tools/extract-cm8-engine.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = process.env.CM8_SRC || 'C:/Users/shaeg/Downloads/index_8.html';
const OUT = path.join(HERE, '..', 'src', 'cm8', 'foods.ts');

const html = fs.readFileSync(SRC, 'utf8');

// Pull the engine IIFE out of its <script> block.
const start = html.indexOf('window.CM8N = (function()');
if (start < 0) throw new Error('CM8N engine not found in source');
const end = html.indexOf('</script>', start);
const source = html.slice(start, end);

const sandbox = { window: {}, document: undefined, console };
vm.createContext(sandbox);
vm.runInContext(source, sandbox, { timeout: 5000 });

const N = sandbox.window.CM8N;
if (!N || !Array.isArray(N.FOODS)) throw new Error('engine did not expose FOODS');

// FOODS entries carry a names[] plus per-serving nutrients; keep every field.
const foods = N.FOODS.map((f) => ({
  names: f.names,
  unit: f.unit,
  qty: f.qty,
  kcal: f.kcal, p: f.p, c: f.c, f: f.f,
  fib: f.fib, ca: f.ca, fe: f.fe, vc: f.vc,
  caf: f.caf, fluid: f.fluid,
  cat: f.cat,
}));

const banner = '/* AUTO-GENERATED by tools/extract-cm8-engine.mjs - do not edit by hand.\n'
  + ' * These are CM8\'s own nutrition tables, serialised by running its engine,\n'
  + ' * so Atlas scores a meal exactly the way CM8 does. */\n\n';

const body = banner
  + 'export type FoodCat = ' + [...new Set(foods.map((f) => f.cat))].map((c) => JSON.stringify(c)).join(' | ') + ';\n\n'
  + 'export interface FoodRow {\n'
  + '  names: string[];\n  unit: string;\n  qty: number;\n'
  + '  kcal: number; p: number; c: number; f: number;\n'
  + '  fib: number; ca: number; fe: number; vc: number;\n'
  + '  caf: number; fluid: number;\n  cat: FoodCat;\n}\n\n'
  + 'export const FOODS: FoodRow[] = ' + JSON.stringify(foods, null, 2) + ';\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body, 'utf8');

const byCat = foods.reduce((m, f) => { m[f.cat] = (m[f.cat] || 0) + 1; return m; }, {});
console.log('extracted -> src/cm8/foods.ts');
console.log('  foods ' + foods.length + '  (' + Object.entries(byCat).map(([k, v]) => k + ':' + v).join(', ') + ')');
console.log('  names ' + foods.reduce((s, f) => s + f.names.length, 0) + ' searchable aliases');

// Sanity: the engine's own maths, so a bad port is caught here rather than in the UI.
const t = N.targets({ training: 'full', weightKg: 55 });
console.log('  targets@55kg full: ' + t.kcal + ' kcal, ' + t.p + 'g protein, ' + t.c + 'g carbs, ca ' + t.ca + ', fe ' + t.fe);
const parsed = N.parse('eggs with avocado and cheese');
console.log('  parse check: ' + parsed.items.map((i) => i.name).join(' + ') + ' -> ' + Math.round(N.sum(parsed.items).p) + 'g protein');
const coffee = N.parse('a light coffee');
console.log('  drink check: ' + N.classify(coffee, 'Snack') + ', caffeine ' + Math.round(N.sum(coffee.items).caf) + 'mg');
